"""Onboarding: plug a new existing application into the foundation with configuration only.

    aiready app init crm --base-url https://crm.internal --whoami /api/me --session-cookie CRMSESSION \\
        --openapi https://crm.internal/openapi.json --docs /mnt/shares/crm-docs --owner-team sales-platform
    aiready app check crm
    aiready app list

``init`` writes ``config/apps/<app>/`` - one small, commented file per concern, deep-merged into the platform
configuration like every other file (lists such as validators, tool sources and ingestion sources are
appended, so nothing existing is edited). The application itself is not touched: the foundation reaches it
through its login ("who am I" endpoint), its existing API (OpenAPI -> MCP tools, every call as the user) and
its documents / read replica (ingestion with access tags).
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Optional

import httpx
import typer
import yaml

from aiready.cli.common import console, fail, ok, table

app_app = typer.Typer(help="Onboard existing applications (config only, the application is not modified).",
                      no_args_is_help=True)

_NAME = re.compile(r"^[a-z][a-z0-9-]{1,40}$")
HEADER = "# Generated by `aiready app init {app}`. Edit freely: this file is plain platform configuration.\n"


def _dump(data: dict[str, Any], note: str, app: str) -> str:
    return HEADER.format(app=app) + "".join(f"# {line}\n" for line in note.strip().splitlines()) + "\n" + \
        yaml.safe_dump(data, sort_keys=False, width=110)


def scaffold(app: str, *, base_url: str, whoami: str, session_cookie: str | None, openapi: str | None,
             docs: str | None, replica_url: str | None, owner_team: str, tenant: str, user_roles: list[str],
             origins: list[str]) -> dict[str, str]:
    """Return {filename: content} for config/apps/<app>/."""
    env = re.sub(r"[^A-Z0-9]", "_", app.upper())
    base = f"${{{env}_URL:-{base_url.rstrip('/')}}}"
    users_role, users_group = f"{app}-user", f"{app}-users"
    files: dict[str, str] = {}

    files["app.yaml"] = _dump({
        "apps": {app: {"display_name": app.replace("-", " ").title(), "owner_team": owner_team,
                       "collection": f"{app}-kb", "default_workflow": f"{app}_assistant",
                       "allowed_origins": origins, "data_class_default": "internal"}},
        "assistant": {"apps": {app: {"title": f"{app.replace('-', ' ').title()} assistant",
                                     "workflow": f"{app}_assistant", "collection": f"{app}-kb",
                                     "allowed_origins": origins}}},
        "gateway": {
            "rate_limits": {f"{app}-app": {"scope": "app", "match": app, "requests": 1200, "window_seconds": 60}},
            "budgets": {f"{app}-monthly": {"scope": "app", "match": app, "period": "month",
                                           "max_tokens": 50_000_000, "action": "warn"}},
        },
    }, "Registration, assistant widget settings, rate limit and token budget for the application.\n"
       "Switch the budget action to `block` once usage is understood.", app)

    validator: dict[str, Any] = {
        "type": "introspect_http", "name": f"{app}-session", "app": app,
        "url": base + (whoami if whoami.startswith("/") else "/" + whoami), "method": "GET",
        "timeout": 5, "cache_ttl": 30,
        "mappings": {"sub": "$.login", "email": "$.email", "name": "$.name", "tenant": "$.tenant",
                     "roles": "$.roles"},
        "role_mapping": {"default_roles": ["user"], "keep_unmapped_roles": False, "rules": [
            {"app_role": r, "roles": [users_role], "groups": [users_group]} for r in user_roles]},
    }
    if session_cookie:
        validator["session_cookie"] = session_cookie
    else:
        validator["forward_headers"] = ["Authorization"]
    files["identity.yaml"] = _dump(
        {"integration": {"identity_bridge": {"validators": [validator]}}},
        "Identity: the app's own login is trusted through its 'who am I' endpoint. Adjust `mappings` (JSONPath into\n"
        "that endpoint's response) and map the app's roles to platform roles/groups. Unmapped app roles give no\n"
        "rights. Users then exchange their app session at POST /v1/token on the identity bridge.", app)

    if openapi:
        spec_url = openapi if openapi.startswith("http") else base + (openapi if openapi.startswith("/") else "/" + openapi)
        files["tools.yaml"] = _dump({"tools": {"sources": [{
            "name": app, "spec_url": spec_url, "base_url": base, "prefix": f"{app}_",
            "include": [], "exclude": ["tag:internal", "tag:admin"], "timeout_seconds": 30,
            "data_class": "internal", "required_roles": [users_role]}]}},
            "Agent tools: one MCP tool per operation of the app's existing API, called with the user's own identity.\n"
            "GET = read (runs freely); POST/PUT/PATCH = write and DELETE = delete (wait for an approver).\n"
            "Narrow with include/exclude globs; override effects per tool under tools.overrides.", app)

    sources: list[dict[str, Any]] = []
    if docs:
        sources.append({
            "name": f"{app}-docs", "collection": f"{app}-kb", "app": app, "tenant": tenant,
            "connector": {"type": "filesystem", "root": docs, "include": ["**/*.md", "**/*.pdf", "**/*.docx",
                                                                          "**/*.html", "**/*.txt"]},
            "access_tags": [], "require_access_tags": True, "data_class": "internal", "schedule": "every 30m",
            "verify": [{"question": "REPLACE with a question the documents answer", "expect_doc_contains":
                        "REPLACE-with-a-document-name", "top_k": 5}]})
    if replica_url:
        sources.append({
            "name": f"{app}-db", "collection": f"{app}-records", "app": app, "tenant": tenant, "enabled": False,
            "connector": {"type": "sql", "url": replica_url, "tables": [
                {"table": "REPLACE_table", "key_columns": ["id"], "updated_at_column": "updated_at",
                 "title_template": "REPLACE {id}", "exclude_columns": [],
                 "access_tags": [users_group]}]},
            "require_access_tags": True, "data_class": "internal", "schedule": "every 15m"})
    if sources:
        files["ingestion.yaml"] = _dump(
            {"ingestion": {"sources": sources}},
            "Knowledge: documents (and optionally rows from the READ REPLICA - never the live database) indexed with\n"
            "access tags. Every file needs an access list (.acl.json sidecar or path map) or it is not indexed.\n"
            "Fill in the verification question so each load proves the content can be found.", app)

    files["workflows.yaml"] = _dump({"workflows": {
        f"{app}_assistant": {"version": "1", "description": f"{app} assistant - knowledge questions and app actions.",
                             "pattern": "router", "model": "small", "default": "knowledge", "routes": {
                                 "knowledge": {"workflow": "retrieval_chain",
                                               "description": "questions about documents, policies and procedures"},
                                 "actions": {"workflow": f"{app}_agent",
                                             "description": f"looking up or changing records in {app}"}}},
        f"{app}_agent": {"version": "1", "description": f"Agent loop over the {app} tools; writes wait for approval.",
                         "pattern": "agent_loop", "tools": [f"{app}_*", "search_knowledge"],
                         "limits": {"max_steps": 15, "max_tool_calls": 8}}}},
        "Orchestration: a router sends knowledge questions to retrieval and record work to an agent loop over this\n"
        "app's tools only. Limits cap steps per run; every write tool pauses for a person.", app)

    files["policies.yaml"] = _dump({"policies": {app: {
        "version": "1.0.0", "description": f"Rules specific to {app}.",
        "rules": [
            {"id": f"{app}.tools.users_only", "description": f"{app} tools are for {app} users.",
             "action": "tool.call", "effect": "deny",
             "when": {"resource.tool": {"glob": f"{app}_*"}, "not": {"principal.roles": {"contains": users_role}}}},
            {"id": f"{app}.deletes.need_approval", "description": "Deletions in this app always wait for a person.",
             "action": "tool.call", "effect": "require_approval",
             "when": {"resource.tool": {"glob": f"{app}_*"}, "resource.effect": "delete"}},
        ]}}},
        "Governance specific to this app, on top of the platform-wide rules in config/policies/. Test changes with\n"
        "`aiready policy test` before they hot-reload.", app)

    files["evals.yaml"] = _dump({"evals": {"suites": {app: {
        "version": "1", "description": f"{app} assistant - golden questions from real users.",
        "target": {"type": "rag", "collection": f"{app}-kb", "feature": f"{app}-assistant"},
        "personas": {"default": {"sub": f"eval-{app}", "roles": [users_role], "groups": [users_group]}},
        "thresholds": {"grounding": 0.7},
        "cases": [{"id": f"{app}-001", "question": "REPLACE with a real user question",
                   "must_include": ["REPLACE"], "expected_sources": [], "tags": ["smoke"]}]}}}},
        "Evaluation: the release gate runs this suite (plus the safety suites) and blocks a release that scores\n"
        "lower. Build it from real questions; every reviewed failure becomes a new case.", app)

    files["README.md"] = f"""# {app} on the AI foundation

Generated by `aiready app init {app}`. The application is not modified; it is reached through:

| Concern | File | What to fill in |
|---|---|---|
| Registration, widget, budgets | `app.yaml` | origins allowed to embed the widget, budget action |
| Login | `identity.yaml` | JSONPath mappings of the who-am-I response, app role -> platform role/group rules |
| Agent tools (MCP) | `tools.yaml` | include/exclude operations; effects per tool in `tools.overrides` |
| Knowledge | `ingestion.yaml` | access lists for documents, replica tables, a verification question |
| Orchestration | `workflows.yaml` | routes and tool allow-list |
| Governance | `policies.yaml` | app-specific rules |
| Evaluation | `evals.yaml` | golden questions from real users |

Then:

```bash
aiready config validate          # schema + policy compilation
aiready policy test              # policy CI cases
aiready app check {app}          # reachability of login, API spec and documents
aiready ingest run --source {app}-docs
aiready eval run {app} --release <version> && aiready eval gate {app} --release <version>
```

Embed the assistant in the app's pages with one tag:

```html
<script src="https://<assistant-host>/widget/assistant-widget.js" data-app="{app}"
        data-endpoint="https://<assistant-host>" data-token-endpoint="https://<bridge-host>/v1/token"></script>
```
"""
    return files


@app_app.command("init")
def app_init(name: str = typer.Argument(..., help="Short app id: lowercase letters, digits, dashes."),
             base_url: str = typer.Option(..., help="Where the existing application is reachable."),
             whoami: str = typer.Option("/api/me", help="The app's endpoint returning the signed-in user."),
             session_cookie: Optional[str] = typer.Option(None, help="Session cookie name (omit for bearer-token apps)."),
             openapi: Optional[str] = typer.Option(None, help="OpenAPI spec URL or path on the app (-> MCP tools)."),
             docs: Optional[str] = typer.Option(None, help="Document share to index (path on the ingestion worker)."),
             replica_url: Optional[str] = typer.Option(None, help="READ REPLICA URL for record ingestion (optional)."),
             owner_team: str = typer.Option("unassigned"), tenant: str = "default",
             user_role: list[str] = typer.Option(["user"], "--user-role", help="App roles that may use the assistant."),
             origin: list[str] = typer.Option([], "--origin", help="Origins allowed to embed the widget."),
             config_dir: Path = typer.Option(Path("config")), force: bool = False):
    """Generate config/apps/<name>/ for a new application."""
    if not _NAME.match(name):
        fail("app name must match ^[a-z][a-z0-9-]{1,40}$")
    target = config_dir / "apps" / name
    if target.exists() and not force:
        fail(f"{target} exists (use --force to overwrite)")
    files = scaffold(name, base_url=base_url, whoami=whoami, session_cookie=session_cookie, openapi=openapi,
                     docs=docs, replica_url=replica_url, owner_team=owner_team, tenant=tenant,
                     user_roles=user_role, origins=origin or [base_url.rstrip("/")])
    target.mkdir(parents=True, exist_ok=True)
    for fname, content in files.items():
        (target / fname).write_text(content)
    ok(f"wrote {len(files)} files to {target}")
    console.print(f"next: edit the REPLACE markers, then `aiready config validate` and `aiready app check {name}`")


@app_app.command("list")
def app_list(config_dir: Path = typer.Option(Path("config"))):
    """Applications onboarded, and which parts of the foundation each one uses."""
    from aiready.core.config import ConfigStore

    store = ConfigStore(config_dir)
    tree = store.tree
    rows = []
    for name, spec in (tree.get("apps") or {}).items():
        validators = [v for v in (tree.get("integration", {}).get("identity_bridge", {}).get("validators") or [])
                      if v.get("app") == name]
        sources = [s for s in (tree.get("ingestion", {}).get("sources") or []) if s.get("app") == name]
        tools = [s for s in (tree.get("tools", {}).get("sources") or []) if s.get("name") == name]
        rows.append({"app": name, "owner": spec.get("owner_team", ""), "workflow": spec.get("default_workflow", ""),
                     "login": ", ".join(v.get("name", "") for v in validators) or "(bridge default)",
                     "tool sources": len(tools), "ingestion sources": len(sources),
                     "eval suite": "yes" if name in (tree.get("evals", {}).get("suites") or {}) else "no"})
    table(rows, ["app", "owner", "workflow", "login", "tool sources", "ingestion sources", "eval suite"], "applications")


@app_app.command("check")
def app_check(name: str, config_dir: Path = typer.Option(Path("config")), timeout: float = 5.0):
    """Check that the foundation can reach the app's login endpoint, API spec and documents."""
    from aiready.core.config import ConfigStore

    tree = ConfigStore(config_dir).tree
    if name not in (tree.get("apps") or {}):
        fail(f"app '{name}' is not registered (apps.{name})")
    rows, failed = [], 0

    def probe(what: str, url: str, expect: set[int]) -> None:
        nonlocal failed
        try:
            code = httpx.get(url, timeout=timeout).status_code
            good = code in expect
            rows.append({"check": what, "target": url, "result": f"HTTP {code}" + ("" if good else " (unexpected)")})
        except httpx.HTTPError as exc:
            good = False
            rows.append({"check": what, "target": url, "result": f"unreachable: {exc}"})
        failed += 0 if good else 1

    for v in tree.get("integration", {}).get("identity_bridge", {}).get("validators") or []:
        if v.get("app") == name and v.get("url"):
            probe("login (who-am-I, expects 401 without a session)", v["url"], {200, 401, 403})
    for s in tree.get("tools", {}).get("sources") or []:
        if s.get("name") == name and s.get("spec_url"):
            probe("API spec (-> MCP tools)", s["spec_url"], {200})
    for s in tree.get("ingestion", {}).get("sources") or []:
        if s.get("app") == name and s.get("connector", {}).get("type") == "filesystem":
            root = Path(s["connector"].get("root", ""))
            exists = root.exists()
            failed += 0 if exists else 1
            rows.append({"check": f"documents ({s['name']})", "target": str(root),
                         "result": "found" if exists else "missing on this host"})
    suite = (tree.get("evals", {}).get("suites") or {}).get(name)
    placeholders = "REPLACE" in yaml.safe_dump(suite or {}) or any(
        "REPLACE" in yaml.safe_dump(s) for s in tree.get("ingestion", {}).get("sources") or [] if s.get("app") == name)
    rows.append({"check": "placeholders filled in", "target": f"config/apps/{name}",
                 "result": "REPLACE markers remain" if placeholders else "ok"})
    table(rows, ["check", "target", "result"], f"app {name}")
    raise typer.Exit(1 if failed else 0)
