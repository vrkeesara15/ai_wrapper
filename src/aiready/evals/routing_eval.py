"""Routing evaluation: which models are good enough for each task?

The gateway routes each task to the *smallest model that passes its evaluation* (cheapest, fastest), with the
larger ones as fallbacks. This module produces that "eval pass list": every candidate model runs each task's
suite through the gateway (``model=<candidate>``), is judged by the release-gate thresholds (absolute only -
there is no baseline for a new model), and the passing models are listed smallest first.

The output is a YAML snippet for the gateway routing configuration - a routing change, never a code change.
"""

from __future__ import annotations

from typing import Any, Callable

import yaml
from pydantic import BaseModel, Field

from aiready.core.audit import get_audit
from aiready.core.identity import Principal
from aiready.evals.gate import GateConfig, evaluate_gate
from aiready.evals.golden import EvalSuite
from aiready.evals.runner import EvalRunner, ScorecardHistory
from aiready.evals.targets import GatewayTarget, Target
from aiready.observability.governance import service_principal


class ModelCandidate(BaseModel):
    name: str  # gateway model / route name
    size: float = 0.0  # parameters in billions (or any rank: smaller = preferred)
    cost_per_1k_tokens: float = 0.0


class CandidateResult(BaseModel):
    model: str
    size: float
    passed: bool
    overall: float
    pass_rate: float
    latency_p95_ms: float | None = None
    cost_per_case: float | None = None
    failures: list[str] = Field(default_factory=list)


class TaskRouting(BaseModel):
    task: str
    suite: str
    results: list[CandidateResult]
    pass_list: list[str]  # passing models, smallest first
    chosen: str | None  # smallest passing model

    @property
    def fallbacks(self) -> list[str]:
        return self.pass_list[1:]


class RoutingEvalReport(BaseModel):
    release: str
    tasks: list[TaskRouting]

    def to_config(self) -> dict[str, Any]:
        """Snippet merged into the gateway configuration (``gateway.task_routes``)."""
        routes: dict[str, Any] = {}
        for t in self.tasks:
            routes[t.task] = {"eval_pass_list": t.pass_list, "model": t.chosen, "fallbacks": t.fallbacks,
                              "evaluated_release": self.release, "suite": t.suite}
        return {"gateway": {"task_routes": routes}}

    def to_yaml(self) -> str:
        head = (f"# Generated by aiready.evals.routing_eval for release {self.release}.\n"
                "# eval_pass_list: models that passed the task's evaluation, smallest first.\n"
                "# A task with an empty list keeps its current route - no model passed.\n")
        return head + yaml.safe_dump(self.to_config(), sort_keys=False)

    def to_markdown(self) -> str:
        lines = [f"# Routing evaluation ({self.release})", ""]
        for t in self.tasks:
            lines += [f"## {t.task} (suite `{t.suite}`) -> **{t.chosen or 'no model passed'}**", "",
                      "| Model | Size | Passed | Overall | Pass rate | p95 ms | Failures |", "|---|---|---|---|---|---|---|"]
            for r in t.results:
                lines.append(f"| {r.model} | {r.size:g} | {'yes' if r.passed else 'no'} | {r.overall:.3f} | {r.pass_rate:.1%} | "
                             f"{'-' if r.latency_p95_ms is None else f'{r.latency_p95_ms:.0f}'} | {', '.join(r.failures) or '-'} |")
            lines.append("")
        return "\n".join(lines)


async def evaluate_routes(tasks: dict[str, EvalSuite], candidates: list[ModelCandidate], *,
                          gate: GateConfig | None = None, release: str = "routing-eval",
                          target_factory: Callable[[str], Target] | None = None, concurrency: int = 4,
                          stop_at_first_pass: bool = False, operator: Principal | None = None,
                          default_min_pass_rate: float = 0.9) -> RoutingEvalReport:
    """Run every task suite against every candidate (smallest first) and build the pass lists.

    ``stop_at_first_pass`` saves GPU time when only the cheapest passing model is wanted; the default runs all
    candidates so the pass list holds the fallbacks too. Without a baseline, "passes" needs an absolute bar:
    the gate's ``min_pass_rate`` or, when unset, ``default_min_pass_rate`` of the cases.
    """
    gate = gate or GateConfig()
    update: dict[str, Any] = {"require_baseline": False}
    if gate.min_pass_rate is None:
        update["min_pass_rate"] = default_min_pass_rate
    gate = gate.model_copy(update=update)
    factory = target_factory or (lambda m: GatewayTarget(model=m))
    ordered = sorted(candidates, key=lambda c: (c.size, c.cost_per_1k_tokens))
    history = ScorecardHistory()
    out: list[TaskRouting] = []
    for task, suite in tasks.items():
        results: list[CandidateResult] = []
        for cand in ordered:
            runner = EvalRunner(factory(cand.name), concurrency=concurrency, history=history)
            card = await runner.run(suite, release=f"{release}:{cand.name}", operator=operator, save=False,
                                    metadata={"task": task, "model": cand.name})
            verdict = evaluate_gate([card], {}, gate)
            results.append(CandidateResult(model=cand.name, size=cand.size, passed=verdict.passed, overall=card.overall,
                                           pass_rate=card.pass_rate, latency_p95_ms=card.latency_p95_ms,
                                           cost_per_case=card.cost_per_case,
                                           failures=[f"{c.name}" for c in verdict.failures()]))
            if verdict.passed and stop_at_first_pass:
                break
        passing = [r.model for r in results if r.passed]
        out.append(TaskRouting(task=task, suite=suite.name, results=results, pass_list=passing,
                               chosen=passing[0] if passing else None))
    report = RoutingEvalReport(release=release, tasks=out)
    get_audit().for_principal(operator or service_principal("evals"), "evals.routing_eval", resource=release,
                              decision="completed", routes={t.task: t.chosen for t in out})
    return report
